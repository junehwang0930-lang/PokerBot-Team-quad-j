_HOLE_PAIRS = tuple(combinations(range(5), 2))
_BOARD_TRIPLES = {n: tuple(combinations(range(n), 3)) for n in (3, 4, 5)}
_CARD_BITS = tuple(1 << c for c in range(36))
_FIVE_SCORES = get_table()


def _build_fast_tables():
    """Immutable 18 MB pair/triple table; built before the thinking clock."""
    pairs = np.array(list(combinations(range(36), 2)), dtype=np.int32)
    pair_ids = np.zeros((36, 36), dtype=np.int32)
    for i, (a, b) in enumerate(pairs):
        pair_ids[a, b] = pair_ids[b, a] = i
    triple_ids = np.zeros((36, 36, 36), dtype=np.int32)
    for i, cards in enumerate(combinations(range(36), 3)):
        for a, b, c in permutations(cards):
            triple_ids[a, b, c] = i
    cards = np.array(list(combinations(range(36), 5)), dtype=np.int32)
    # Do not depend on the insertion order of the referee's score dictionary.
    masks = np.left_shift(np.uint64(1), cards.astype(np.uint64)).sum(axis=1)
    scores = np.fromiter((_FIVE_SCORES[int(m)] for m in masks), dtype=np.int32,
                         count=len(cards))
    lookup = np.zeros((630, 7140), dtype=np.int32)
    for i, j in _HOLE_PAIRS:
        k, l, m = (v for v in range(5) if v != i and v != j)
        lookup[pair_ids[cards[:, i], cards[:, j]],
               triple_ids[cards[:, k], cards[:, l], cards[:, m]]] = scores
    for array in (pairs, pair_ids, triple_ids, lookup):
        array.flags.writeable = False
    return pairs, pair_ids, triple_ids, lookup


