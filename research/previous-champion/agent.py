def _preflop_equity(hole):
    """Cheap suit-invariant equity against a uniformly random five-card hand."""
    key = sum(1 << ((c >> 2)*3) for c in hole)
    value = _PREFLOP_BASE[key]
    suited = 0
    for suit in range(4):
        ranks = sorted(c >> 2 for c in hole if c & 3 == suit)
        count = len(ranks)
        if count >= 2:
            suited += 1
            hi, lo = ranks[-1], ranks[-2]
            value += _SUIT_COEF[hi*(hi-1)//2+lo] * (1.0,0.60,0.30,0.12)[count-2]
            if count >= 3:
                value += _SUIT_COEF[36+count-3]
    if suited == 2:
        value += _SUIT_COEF[39]
    if suited == 0:
        value += _SUIT_COEF[40]
    return value


def _preflop_quality(holes):
    """Vectorized version of the same model, for opponent-range samples."""
    ranks, suits = holes >> 2, holes & 3
    keys = np.left_shift(1, ranks*3).sum(axis=1)
    value = _PREFLOP_VALUES[np.searchsorted(_PREFLOP_KEYS, keys)].copy()
    suitable = np.zeros(len(holes), dtype=np.int32)
    for suit in range(4):
        mask = suits == suit
        count = mask.sum(axis=1)
        ordered = np.sort(np.where(mask,ranks,-1),axis=1)
        hi, lo = ordered[:,-1], ordered[:,-2]
        valid = count >= 2
        factor = np.where(count==2,1.0,np.where(count==3,0.60,np.where(count==4,0.30,0.12)))
        idx = np.maximum(0, hi*(hi-1)//2+lo)
        value += np.where(valid, _SUIT_ARRAY[idx]*factor, 0.0)
        value += (count==3)*_SUIT_COEF[36] + (count==4)*_SUIT_COEF[37] + (count==5)*_SUIT_COEF[38]
        suitable += valid
    value += (suitable==2)*_SUIT_COEF[39] + (suitable==0)*_SUIT_COEF[40]
    return value


