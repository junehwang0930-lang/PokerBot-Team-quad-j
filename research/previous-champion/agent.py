def _batch_scores(holes, boards):
    """Exact PLO scores for arrays of holdings and 3, 4, or 5 board cards."""
    pairs = _PAIR_IDS[holes[:, _PI], holes[:, _PJ]]
    i, j, k = _BI[boards.shape[1]]
    triples = _TRIPLE_IDS[boards[:, i], boards[:, j], boards[:, k]]
    return _LOOKUP[pairs[:, :, None], triples[:, None, :]].max(axis=(1, 2))


def _sample_cards(rng, available, count, width):
    """Independent uniform ordered samples, without replacement in each row."""
    order = rng.random((count, len(available))).argsort(axis=1)[:, :width]
    return available[order]


def _pair_scores(board):
    triples = [_TRIPLE_IDS[a, b, c] for a, b, c in combinations(board, 3)]
    return _LOOKUP[:, triples].max(axis=1)


def _partial_score(hole, board):
    hm = [_CARD_BITS[a] | _CARD_BITS[b] for a, b in combinations(hole, 2)]
    bm = [_CARD_BITS[a] | _CARD_BITS[b] | _CARD_BITS[c]
          for a, b, c in combinations(board, 3)]
    return max(_FIVE_SCORES[h | b] for h in hm for b in bm)


